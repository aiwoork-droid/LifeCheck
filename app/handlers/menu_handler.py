                "📖 <b>Как пользоваться</b>\n\n"

                "☀️ <b>Сегодня</b>\n"
                "Здесь собрана информация за текущий день: "
                "вода, туалет, давление, сахар, сон, работа, "
                "мигрень и привычки.\n\n"

                "❤️ <b>Здоровье</b>\n"
                "Здесь можно записывать давление, мигрень "
                "и сахар в крови.\n\n"

                "📊 <b>Статистика</b>\n"
                "Показывает показатели за день, неделю, "
                "месяц и год.\n\n"

                "📝 <b>Мой день</b>\n"
