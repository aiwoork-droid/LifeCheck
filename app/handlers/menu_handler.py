                "<code>2</code> — 📝 Мой день\n"
                "<code>3</code> — ⭐ Привычки\n"
                "<code>4</code> — ❤️ Здоровье\n"
                "<code>5</code> — 📊 Статистика\n"
                "<code>6</code> — ⚙️ Настройки\n"
